#!/bin/sh
# Regenerate docs/CLI.md from the CLI's own --help output, so the reference
# cannot drift from the actual flags. Run after changing src/config.rs.
set -eu
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
BIN=${1:-$ROOT/target/release/vpncloud}

if [ ! -x "$BIN" ]; then
  echo "Build first: cargo build --release --features installer,wizard,websocket" >&2
  exit 1
fi

OUT="$ROOT/docs/CLI.md"
{
  echo "# CLI reference"
  echo
  echo "> Generated by \`docs/gen-cli-reference.sh\`. Do not edit by hand."
  echo
  for cmd in "" check-config doctor status network genkey sign-config ws-proxy migrate-config completion config install service; do
    if [ -z "$cmd" ]; then
      echo "## \`vpncloud --help\`"
      echo
      echo '```text'
      "$BIN" --help
      echo '```'
    else
      HELP=$("$BIN" "$cmd" --help 2>/dev/null || true)
      case "$HELP" in
        *"Usage: vpncloud $cmd"*)
          echo "## \`vpncloud $cmd --help\`"
          echo
          echo '```text'
          echo "$HELP"
          echo '```'
          ;;
        *) echo "<!-- \`vpncloud $cmd\` unavailable on this platform -->" ;;
      esac
    fi
    echo
  done
} > "$OUT"
echo "Wrote $OUT"
